import { CONSULT_SECTIONS, type ConsultSection, type ContextConflict, type EvidenceTrust, FACT_CATEGORIES, type FactCategory, type MultimodalSummary, type PendingReview, type RoiStats, type SummarySection, VITAL_ORDER, type VitalKind } from '@adaxai/contracts'
import { THERMAL_LABEL_IMPORTED } from '../thermal/summary.ts'
import type { SourceKey } from './build.ts'
import { quote, vitalText } from './conflicts.ts'

/**
 * D2: the multimodal summary (`multimodal-summary-v2`). Composed by FIXED RULES from what the consultation context read (no language model is
 * asked, and no AI text is made here): ADVISORY, for the doctor, who decides. Deterministic: the same inputs give the same statements.
 *
 * What it may say, and what it may not:
 *   - presentation: the reason for the visit (as entered) and the important points the doctor CONFIRMED, quoted;
 *   - patient: allergies (or that none is recorded, or that the status is not recorded), open conditions and current medicines, from the record;
 *   - observations: staff vital signs; a device reading ONLY as "device reading, unverified", and never a simulated one; the measurements of an
 *     APPROVED thermal image that is not simulated (minimum, maximum, mean, and per region), after how it arrived when it is not a live capture
 *     (IMPORTED, UPLOADED); a stethoscope recording only as "recording available for clinician review; not analysed": no thermal, stethoscope
 *     or wearable finding is ever stated;
 *   - ai: only the statements of the AI draft that the doctor ACCEPTED or EDITED, quoted as reviewed, and counts of what waits; never new AI text;
 *   - review: what waits, each conflict as found (never resolved), what is missing, and the limitations.
 * A source that could not be read is said to be so: nothing is then said to be absent. Every statement carries how far it can be trusted and the
 * evidence items it rests on. Nothing in it is a diagnosis, a prescription or a recommendation. Change the version when the wording or what is
 * stated changes.
 *
 * v2: a device reading's state word is left out (it changes with time; the time it was measured is stated); an approved image that is not a live
 * capture says how it arrived, first; a source that could not be read is no longer stated as an absence.
 */
export const SUMMARY_COMPOSER_VERSION = 'multimodal-summary-v2'

export const SUMMARY_ADVISORY = 'Advisory: composed by fixed rules from this consultation’s records; the doctor decides.'
export const SUMMARY_SIMULATED = 'SIMULATED items (generated by a simulator) are listed for what they are and are not part of this summary.'
export const NOT_ANALYSED = 'recording available for clinician review; not analysed'

/** Region statistics of an approved thermal image stated one by one; any beyond are counted (the thermal tool shows them all). */
const THERMAL_REGIONS_STATED = 6
/** Record entries, confirmed points and reviewed statements stated one by one; any beyond are counted. */
const LISTED = 10

export interface SummaryInput {
  reasonForVisit: string | null
  /** Points the doctor accepted or edited (null: not shown to this viewer, or could not be read; `unread` says which). */
  confirmedPoints: { itemId: string; category: string; text: string }[] | null
  /** How many points the doctor accepted or edited in all (`confirmedPoints` holds the newest of them). */
  confirmedCount?: number
  /** Null when the record could not be read. */
  record: {
    allergies: { substance: string; severity: string }[]
    noKnownAllergies: boolean
    conditions: { name: string; status: string }[]
    medications: { drugName: string; strength: string | null; dose: string; frequency: string }[]
  } | null
  /** Staff measurements at this visit, newest first (null: could not be read). */
  staffVitals: { itemId: string; kind: VitalKind; value: number; measuredAt: Date }[] | null
  /** The newest reading of each kind from each device at this visit (null: could not be read). */
  deviceReadings: { itemId: string; kind: VitalKind; value: number; measuredAt: Date; label: string; simulated: boolean }[] | null
  /** This consultation's thermal images (null: could not be read). `capturedAt` is when the camera says it took the image, null when nothing said. */
  thermal: { itemId: string; region: string; status: string; simulated: boolean; captureSource: string; capturedAt: Date | null; minC: number; maxC: number; meanC: number; rois: { label: string; stats: RoiStats }[] }[] | null
  /** Null: could not be read. */
  stethoscope: { itemId: string; site: string; durationMs: number | null; simulated: boolean }[] | null
  /** The statements of the AI draft shown to the doctor of the consultation ([] when there is none; null: not shown to this viewer, or could not be read). */
  draftStatements: { itemId: string; section: string; text: string; finalText: string | null; decision: string }[] | null
  /** The Mana conversations of this consultation the viewer asked in, and how many answers they hold. */
  mana: { itemIds: string[]; answered: number }
  pending: PendingReview
  pendingItemIds: { points: string[]; draftStatements: string[]; thermalImages: string[]; thermalSummaries: string[] }
  /** How far the important points that wait can be trusted: `extracted` when fixed rules found every one, `model_output` when a model found any. */
  waitingPointsTrust: EvidenceTrust
  /** The sources that could not be read just now (build.ts): what they hold is neither stated nor said to be absent. */
  unread: ReadonlySet<SourceKey>
  conflicts: ContextConflict[]
  missing: string[]
  /** True when the evidence holds anything simulated (it is left out of this summary, and the summary says so). */
  simulatedShown: boolean
  /** What this viewer is not shown (the conversation, the points, the AI draft), in words; null when nothing is held back. */
  hidden: string | null
  /** The clock time of an instant, in the facility's time zone ("10:40"). */
  time: (d: Date) => string
  /** The date and clock time of an instant, in the facility's time zone ("5 Oct 2026, 10:40"). */
  dateTime: (d: Date) => string
}

type Statement = SummarySection['statements'][number]
const st = (text: string, trust: EvidenceTrust, itemIds: string[] = []): Statement => ({ text, trust, itemIds })
const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`
const deg = (v: number) => `${String(Number(v.toFixed(2)))} °C`
const more = (n: number, what: string) => (n > 0 ? ` (and ${n} more ${what})` : '')
const categoryLabel = (c: string) => FACT_CATEGORIES[c as FactCategory] ?? c
const listed = (parts: string[]) => (parts.length < 2 ? parts.join('') : `${parts.slice(0, -1).join(', ')} and ${parts.at(-1)}`)
const capital = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)

/** How an approved image that is not a live capture arrived, before its numbers (V6's and V3's words): they are not of a capture made now. */
const IMPORTED = THERMAL_LABEL_IMPORTED.replace(/\.$/, '')
const UPLOADED = 'UPLOADED: an image file chosen on the thermal pages'

function presentation(i: SummaryInput): Statement[] {
  const out: Statement[] = []
  if (i.reasonForVisit?.trim()) out.push(st(`Reason for visit (as entered at check-in): ${quote(i.reasonForVisit, 160)}.`, 'clinician_entered'))
  for (const p of (i.confirmedPoints ?? []).slice(0, LISTED)) out.push(st(`${categoryLabel(p.category)}: ${quote(p.text, 160)} (an important point confirmed by the doctor).`, 'doctor_reviewed', [p.itemId]))
  const confirmedMore = Math.max(i.confirmedCount ?? 0, i.confirmedPoints?.length ?? 0) - Math.min(i.confirmedPoints?.length ?? 0, LISTED)
  if (confirmedMore > 0) out.push(st(`${plural(confirmedMore, 'more confirmed point is', 'more confirmed points are')} in the conversation tool.`, 'rule_output'))
  // That no point is confirmed is said only to a viewer whose points were read (to anyone else it is not known).
  if (!out.length) out.push(st(i.confirmedPoints ? 'No reason for the visit and no confirmed point is recorded yet.' : 'No reason for the visit is recorded yet.', 'rule_output'))
  if (i.unread.has('points')) out.push(st('The important points could not be read just now; no confirmed point is stated here.', 'rule_output'))
  return out
}

function patient(i: SummaryInput): Statement[] {
  const r = i.record
  if (!r) return [st('The patient’s record could not be read just now: allergies, conditions and medicines are not stated here.', 'rule_output')]
  const out: Statement[] = []
  if (r.allergies.length) {
    const list = r.allergies.slice(0, LISTED).map((a) => (a.severity && a.severity !== 'unknown' ? `${a.substance} (${a.severity})` : a.substance))
    out.push(st(`Allergies on the record: ${list.join(', ')}${more(r.allergies.length - LISTED, 'allergies')}.`, 'clinician_entered'))
  } else if (r.noKnownAllergies) out.push(st('The record states no known allergies.', 'clinician_entered'))
  else out.push(st('Allergy status is not recorded: no allergy, and “no known allergies” is not marked.', 'rule_output'))
  if (r.conditions.length) out.push(st(`Conditions on the record: ${r.conditions.slice(0, LISTED).map((c) => `${c.name} (${c.status})`).join(', ')}${more(r.conditions.length - LISTED, 'conditions')}.`, 'clinician_entered'))
  else out.push(st('No active or controlled condition is on the record.', 'rule_output'))
  if (r.medications.length) {
    const list = r.medications.slice(0, LISTED).map((m) => [m.drugName, m.strength, m.dose, m.frequency].filter(Boolean).join(' '))
    out.push(st(`Current medicines on the record: ${list.join('; ')}${more(r.medications.length - LISTED, 'medicines')}.`, 'clinician_entered'))
  } else out.push(st('No current medicine is on the record.', 'rule_output'))
  return out
}

function observations(i: SummaryInput): Statement[] {
  const out: Statement[] = []
  // The newest staff measurement of each kind, in the order vital signs are read.
  const order = (k: VitalKind) => VITAL_ORDER.indexOf(k)
  const newestStaff = new Map<VitalKind, NonNullable<SummaryInput['staffVitals']>[number]>()
  for (const v of i.staffVitals ?? []) if (!newestStaff.has(v.kind)) newestStaff.set(v.kind, v)
  for (const v of [...newestStaff.values()].sort((a, b) => order(a.kind) - order(b.kind))) {
    out.push(st(`${vitalText(v.kind, v.value)} at ${i.time(v.measuredAt)} (entered by staff).`, 'clinician_entered', [v.itemId]))
  }
  // A device value is said to be what it is: a reading of a device not validated here. A simulator's output is not a reading of anyone. Its state
  // (LIVE, STALE ...) is not stated: it changes as time passes, and the time it was measured is stated.
  for (const d of (i.deviceReadings ?? []).filter((x) => !x.simulated).sort((a, b) => order(a.kind) - order(b.kind) || b.measuredAt.getTime() - a.measuredAt.getTime())) {
    out.push(st(`${vitalText(d.kind, d.value)} at ${i.time(d.measuredAt)}: device reading, unverified (${d.label}).`, 'measured_unverified', [d.itemId]))
  }
  // Only the measurements of an approved image (approval froze them) of a real capture: the numbers as stored, no interpretation. An image that is
  // not a live capture says first how it arrived, and when the camera dated it (or that this is not known): it may not be of this consultation.
  for (const t of (i.thermal ?? []).filter((x) => x.status === 'approved' && !x.simulated)) {
    const taken = t.capturedAt ? `dated ${i.dateTime(t.capturedAt)} by the camera` : 'date taken not known'
    const arrived = t.captureSource === 'gallery_import' ? `${IMPORTED}, ${taken}. ` : t.captureSource === 'file_upload' ? `${UPLOADED}, ${taken}. ` : ''
    const regions = t.rois
      .slice(0, THERMAL_REGIONS_STATED)
      .map((r) => (r.stats.mean === null || !r.stats.pixelCount ? `region ${quote(r.label, 40)}: no pixel with a reading` : `region ${quote(r.label, 40)} min ${deg(r.stats.min!)}, max ${deg(r.stats.max!)}, mean ${deg(r.stats.mean)}`))
    const rest = t.rois.length > THERMAL_REGIONS_STATED ? `; ${plural(t.rois.length - THERMAL_REGIONS_STATED, 'more region', 'more regions')} in the thermal tool` : ''
    out.push(st(`${arrived}Thermal image of ${quote(t.region, 40)} (approved): whole image min ${deg(t.minC)}, max ${deg(t.maxC)}, mean ${deg(t.meanC)}${regions.length ? `; ${regions.join('; ')}` : ''}${rest}. Skin-surface temperature only.`, 'measured', [t.itemId]))
  }
  for (const s of (i.stethoscope ?? []).filter((x) => !x.simulated)) {
    const length = s.durationMs ? `, ${Math.round(s.durationMs / 1000)} s` : ''
    out.push(st(`Stethoscope recording (${s.site}${length}): ${NOT_ANALYSED}.`, 'recorded', [s.itemId]))
  }
  // What could not be read is said to be so, and then nothing is said to be absent.
  const unread = [
    i.staffVitals === null && 'the vital signs entered by staff',
    i.deviceReadings === null && 'the device readings',
    i.thermal === null && 'the thermal images',
    i.stethoscope === null && 'the stethoscope recordings',
  ].filter((x): x is string => !!x)
  if (unread.length) out.push(st(`${capital(listed(unread))} could not be read just now; they are not stated here.`, 'rule_output'))
  else if (!out.length) out.push(st('No observation is recorded in this consultation yet.', 'rule_output'))
  return out
}

function ai(i: SummaryInput): Statement[] {
  const out: Statement[] = []
  const reviewed = (i.draftStatements ?? []).filter((s) => s.decision === 'accepted' || s.decision === 'edited')
  for (const s of reviewed.slice(0, LISTED)) {
    const section = CONSULT_SECTIONS[s.section as ConsultSection] ?? s.section
    out.push(st(`${quote(s.finalText ?? s.text, 300)} (${section}; ${s.decision === 'edited' ? 'edited and accepted' : 'accepted'} by the doctor).`, 'doctor_reviewed', [s.itemId]))
  }
  if (reviewed.length > LISTED) out.push(st(`${plural(reviewed.length - LISTED, 'more reviewed statement is', 'more reviewed statements are')} in the AI draft.`, 'rule_output'))
  if (i.pending.draftStatements) out.push(st(`${plural(i.pending.draftStatements, 'AI draft statement waits', 'AI draft statements wait')} for the doctor’s review; ${i.pending.draftStatements === 1 ? 'it is' : 'they are'} not part of this summary.`, 'model_output', i.pendingItemIds.draftStatements))
  if (i.pending.points) out.push(st(`${plural(i.pending.points, 'extracted important point waits', 'extracted important points wait')} for the doctor’s review; ${i.pending.points === 1 ? 'it is' : 'they are'} not part of this summary.`, i.waitingPointsTrust, i.pendingItemIds.points))
  if (i.mana.answered) out.push(st(`Mana answered ${plural(i.mana.answered, 'question', 'questions')} in this consultation; its answers are not part of this summary.`, 'model_output', i.mana.itemIds))
  // Said only to the one who can see the draft, and only when it was read: anyone else is not told that nothing was accepted, since they cannot know.
  if (i.unread.has('drafts')) out.push(st('The AI draft could not be read just now; nothing of it is stated here.', 'rule_output'))
  else if (i.draftStatements === null) out.push(st('The AI draft of this consultation is shown to its doctor only; nothing of it is stated here.', 'rule_output'))
  else if (!reviewed.length) out.push(st('No statement of an AI draft has been accepted by the doctor in this consultation.', 'rule_output'))
  return out
}

function review(i: SummaryInput): Statement[] {
  const out: Statement[] = []
  const p = i.pending
  if (p.points) out.push(st(`To review: ${plural(p.points, 'important point', 'important points')}.`, 'rule_output', i.pendingItemIds.points))
  if (p.draftStatements) out.push(st(`To review: ${plural(p.draftStatements, 'AI draft statement', 'AI draft statements')}.`, 'rule_output', i.pendingItemIds.draftStatements))
  if (p.thermalImages) out.push(st(`To review: ${plural(p.thermalImages, 'thermal image', 'thermal images')}.`, 'rule_output', i.pendingItemIds.thermalImages))
  if (p.thermalSummaries) out.push(st(`To review: ${plural(p.thermalSummaries, 'thermal summary', 'thermal summaries')}.`, 'rule_output', i.pendingItemIds.thermalSummaries))
  // Each conflict as the rules found it: both sides, nothing resolved.
  for (const c of i.conflicts) out.push(st(`Conflict: ${c.text}`, 'rule_output', c.itemIds))
  for (const m of i.missing) out.push(st(m, 'rule_output'))
  if (i.hidden) out.push(st(i.hidden, 'rule_output'))
  if (i.simulatedShown) out.push(st(SUMMARY_SIMULATED, 'rule_output'))
  out.push(st(SUMMARY_ADVISORY, 'rule_output'))
  return out
}

export function composeSummary(i: SummaryInput): MultimodalSummary {
  return {
    composer: SUMMARY_COMPOSER_VERSION,
    sections: [
      { key: 'presentation', title: 'Current presentation', statements: presentation(i) },
      { key: 'patient', title: 'Patient context', statements: patient(i) },
      { key: 'observations', title: 'Current observations', statements: observations(i) },
      { key: 'ai', title: 'AI-derived information (reviewed by the doctor)', statements: ai(i) },
      { key: 'review', title: 'For the doctor’s review', statements: review(i) },
    ],
  }
}
